/**
 * generateMaze(cols, rows, cellSize)
 * - Uses a simple recursive backtracker to carve a maze in a grid.
 * - Walls are returned as Platform instances sized to cellSize.
 * - The maze start (spawn) is set to the entrance cell center.
 * - The maze end is placed as a WinBlock at the exit cell center.
 */
function generateMaze(cols = 15, rows = 11, cellSize = 120) {
  // grid of cells, walls between; we carve passages and place walls where not carved.
  const total = cols * rows;
  const visited = new Uint8Array(total);
  const stack = [];

  const idx = (c, r) => r * cols + c;
  const inBounds = (c, r) => c >= 0 && r >= 0 && c < cols && r < rows;

  // start in top-left-ish interior cell
  let cx = 1;
  let cy = 1;
  visited[idx(cx, cy)] = 1;
  stack.push({ c: cx, r: cy });

  // carve passages by knocking down walls among a cell grid with 2-step neighbors
  while (stack.length) {
    const cur = stack[stack.length - 1];
    const c = cur.c, r = cur.r;
    const neighbors = [];
    const dirs = [
      { dc: 0, dr: -2 },
      { dc: 2, dr: 0 },
      { dc: 0, dr: 2 },
      { dc: -2, dr: 0 }
    ];
    for (const d of dirs) {
      const nc = c + d.dc;
      const nr = r + d.dr;
      if (inBounds(nc, nr) && !visited[idx(nc, nr)]) neighbors.push(d);
    }

    if (neighbors.length === 0) {
      stack.pop();
      continue;
    }

    const choice = neighbors[Math.floor(Math.random() * neighbors.length)];
    const nc = c + choice.dc;
    const nr = r + choice.dr;
    // mark intermediate cell as passage as well (single-step cell between two path cells)
    const midc = c + choice.dc / 2;
    const midr = r + choice.dr / 2;
    visited[idx(midc, midr)] = 1;
    visited[idx(nc, nr)] = 1;
    stack.push({ c: nc, r: nr });
  }

  // Build platforms: every grid cell that is not visited becomes a wall block
  // We'll offset the maze so it centers reasonably around 0.. based on cellSize
  const platforms = [];
  const mazeWidth = cols * cellSize;
  const mazeHeight = rows * cellSize;
  const offsetX = 0; // keep coordinates positive and relative; Game camera will center
  // Raise the whole maze so the player spawn and passages are higher above the void.
  // Increase this value (more negative) to move the maze further up.
  // Moved maze much higher so falling won't reach the void on maze maps.
  const offsetY = -4200;

  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      if (!visited[idx(c, r)]) {
        const px = offsetX + c * cellSize;
        const py = offsetY + r * cellSize;
        // create a wall block sized to cellSize (use brown/stone color)
        const wall = new Platform(px, py, cellSize, cellSize, '#8d6e63');
        // mark walls from the generated maze so game logic can recognize maze maps
        wall.isMaze = true;
        platforms.push(wall);
      }
      // visited cells are left empty (no thin grey floor platforms)
    }
  }

  // define entrance and exit: entrance at first carved top-left region, exit at bottom-right carved region
  // Find a visited cell on left edge close to top for entrance
  let startCell = null;
  for (let r = 0; r < rows && !startCell; r++) {
    for (let c = 0; c < cols; c++) {
      if (visited[idx(c, r)]) { startCell = { c, r }; break; }
    }
  }
  if (!startCell) startCell = { c: 1, r: 1 };

  // Find exit: search from bottom-right for a visited cell
  let endCell = null;
  for (let r = rows - 1; r >= 0 && !endCell; r--) {
    for (let c = cols - 1; c >= 0; c--) {
      if (visited[idx(c, r)]) { endCell = { c, r }; break; }
    }
  }
  if (!endCell) endCell = { c: cols - 2, r: rows - 2 };

  // Set spawnPoint to entrance center (player should spawn inside the passage)
  spawnPoint = {
    x: offsetX + startCell.c * cellSize + Math.round((cellSize - 40) / 2),
    y: offsetY + startCell.r * cellSize + Math.round((cellSize - 60) / 2)
  };

  // Place a WinBlock at the exit cell center (slightly inset so it's on the floor)
  const winX = offsetX + endCell.c * cellSize + Math.round((cellSize - 120) / 2);
  const winY = offsetY + endCell.r * cellSize + Math.round((cellSize - 20) / 2) - 40;
  const win = new WinBlock(winX, winY, 120, 20, '#ffd600');
  // tag win block as part of maze as well
  win.isMaze = true;
  platforms.push(win);



  return platforms;
}

